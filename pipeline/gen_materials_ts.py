"""Generate web/src/generated/materials.ts from spec/materials.yaml.

Usage (from the repo root):
    python -m pipeline.gen_materials_ts          # validate and write
    python -m pipeline.gen_materials_ts --check  # validate; fail if the .ts is stale
"""

from __future__ import annotations

import argparse
import json
import sys

from pipeline import materials as mat

OUT_PATH = mat.REPO_ROOT / "web" / "src" / "generated" / "materials.ts"


def _js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(p: mat.Palette) -> str:
    ids = list(p.materials)
    lines = [
        "// AUTO-GENERATED by pipeline/gen_materials_ts.py from spec/materials.yaml.",
        "// Do not edit by hand: change the YAML and re-run the generator.",
        "",
        "export type MaterialId =",
        *[f"  | {_js(i)}" for i in ids],
        ";",
        "",
        'export type Shading = "semiconductor" | "dielectric" | "metal";',
        "",
        "export interface MaterialSpec {",
        "  id: MaterialId;",
        "  hex: string;",
        "  shading: Shading;",
        "  dopingTint: boolean;",
        "  /** HTML with <sub>/<sup>; render as markup, not plain text. */",
        "  label: string;",
        "  name: string;",
        "  roughness: number;",
        "  metalness: number;",
        "}",
        "",
        f"export const MATERIAL_IDS: readonly MaterialId[] = {_js(ids)};",
        "",
        "export const MATERIALS: Readonly<Record<MaterialId, MaterialSpec>> = {",
    ]
    for m in p.materials.values():
        lines.append(
            f"  {m.id}: {{ id: {_js(m.id)}, hex: {_js(m.hex)}, shading: {_js(m.shading)}, "
            f"dopingTint: {str(m.doping_tint).lower()}, label: {_js(m.label)}, "
            f"name: {_js(m.name)}, roughness: {m.roughness}, metalness: {m.metalness} }},"
        )
    d = p.doping
    lines += [
        "};",
        "",
        "export const DOPING = {",
        f"  log10Min: {d['log10_min']},",
        f"  log10Max: {d['log10_max']},",
        f"  n: {_js(d['n'])},",
        f"  p: {_js(d['p'])},",
        "} as const;",
        "",
        f"export const ACCENTS = {_js(p.accents)} as const;",
        "",
        f"export const TOOL_HARDWARE = {_js(p.tool_hardware)} as const;",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()

    try:
        palette = mat.load()
    except mat.PaletteError as e:
        print(f"spec/materials.yaml is invalid:\n{e}", file=sys.stderr)
        return 1

    errors, warnings = mat.check_contrast(palette)
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    if errors:
        print("contrast rules failed (STYLE.md §3.1):", file=sys.stderr)
        for e in errors:
            print(f"  {e}", file=sys.stderr)
        return 1

    text = render(palette)
    rel = OUT_PATH.relative_to(mat.REPO_ROOT)
    if args.check:
        current = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.exists() else ""
        if current != text:
            print(f"{rel} is stale: run `python -m pipeline.gen_materials_ts`", file=sys.stderr)
            return 1
        print(f"{rel} is up to date ({len(palette.materials)} materials)")
        return 0

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {rel} ({len(palette.materials)} materials)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
